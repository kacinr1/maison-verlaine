def classify(P,prior,N=None):
    """label from traced contours, or -1 when the point is outside the traced zones"""
    X,Y,Z=P[:,0],P[:,1],P[:,2]; out=np.full(len(P),-1)
    zone=(Z>0.02)&(Y>0.16)&(Y<0.86)&(np.abs(X)<0.17)&(prior!=imn)
    jl,jr=pl(JL,Y),pl(JR,Y)
    lap=zone&(Y<0.83)&(((X<jl)&((Y>0.51)|(X>jl-0.04)))|((X>jr)&((Y>0.51)|(X<jr+0.04))))
    out[lap]=iv
    inner=zone&(X>=jl)&(X<=jr)
    vb=np.interp(X,VB[:,0],VB[:,1])
    trou=inner&(Y<vb)&(X>jl+0.012)&(X<jr-0.012)&(Z<0.162)
    out[trou]=ipa
    inner=inner&~trou
    vl,vr=pl(VL,Y),pl(VR,Y)
    mg=np.clip((Y-0.66)/0.06,0,1)*0.004          # marge près du revers, en haut
    vest=inner&((X<vl+mg)|(X>vr-mg)|(Y<0.583))
    out[vest]=igi
    # haut des bandes de gilet : coupe diagonale parallèle au revers -> parement de veste
    top=vest&(X<0)&(Y>0.69+5.0*(vl-X)); out[top]=ich
    top=vest&(X>0)&(Y>0.69+5.0*(X-vr)); out[top]=ich
    out[inner&~vest]=ich
    # bas : sous les pointes du gilet c'est le pantalon (surface plus en retrait)
    out[vest&(Y<0.235)&(Z<0.158)]=ipa
    # parements intérieurs de la veste : parois latérales (normale surtout en X)
    jl_,jr_=pl(JL,Y),pl(JR,Y)
    band=(out==igi)&((X<jl_+0.012)|(X>jr_-0.012))&(Y<0.72)
    out[band&(Z>0.183)]=iv
    if N is not None:
        lat=np.abs(N[:,0])>0.6*np.hypot(N[:,0],N[:,2])
        wall=(Y<0.80)&(out==igi)&lat&((X<jl_+0.006)|(X>jr_-0.006))
        out[wall]=iv
    hi=(Z>0.02)&(Y>=0.83)&(Y<0.875)&(np.abs(X)<0.17)&(prior==igi); out[hi]=iv
    # côtés du cou : col de chemise (rayon faible) / col de veste
    rr=np.sqrt(X**2+(Z-ZC)**2); rc=np.interp(Y,[0.79,0.83,0.86,0.875],[0.088,0.086,0.082,0.082])
    sd=(Z>=ZC)&(Z<0.03)&(np.abs(X)>0.04)&(Y>0.79)&(Y<0.875)&np.isin(prior,[ich,iv,igi])
    out[sd&(rr<rc)]=ich; out[sd&(rr>=rc)]=iv
    # back of neck
    bk=(Z<ZC)&(np.abs(X)<0.085)&(Y>0.86)&np.isin(prior,[imn,ich,iv])
    b1=0.906-1.5*X**2; b2=0.926-3*X**2
    out[bk&(Y>=b2)]=imn; out[bk&(Y<b2)&(Y>=b1)]=ich; out[bk&(Y<b1)]=iv
    return out
